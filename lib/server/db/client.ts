import "server-only"
import Database from "better-sqlite3"
import { drizzle } from "drizzle-orm/better-sqlite3"
import { migrate } from "drizzle-orm/better-sqlite3/migrator"
import { mkdirSync } from "node:fs"
import { dirname } from "node:path"
import { env } from "../env"
import * as schema from "./schema"

const MIGRATIONS_FOLDER = "drizzle" // generated by drizzle-kit

export function createDb(path = env.DB_PATH) {
    if (path !== ":memory:") {
        mkdirSync(dirname(path), { recursive: true })
    }
    const sqlite = new Database(path)
    sqlite.pragma("journal_mode = WAL")
    sqlite.pragma("foreign_keys = ON")
    const db = drizzle(sqlite, { schema })
    migrate(db, { migrationsFolder: MIGRATIONS_FOLDER })
    return db
}

export type Db = ReturnType<typeof createDb>

const globalForDb = globalThis as typeof globalThis & { __db?: Db }

// Lazy so importing this module (for example during `next build`) never opens the file
export function getDb(): Db {
    return (globalForDb.__db ??= createDb())
}
